/**
 * The six apps as the product names them, READ from the metadata (#2608).
 *
 * The homepage, the docs front page and (with #2606) the two READMEs and the
 * manifest all show the same app list. It drifted while each was typed by
 * hand, so the names now come from where the console reads them: every
 * `src/*\/apps/*.app.ts` the composed stack registers, its `label` for
 * English, and the zh-CN pack's `apps.<name>.label` for Simplified Chinese.
 *
 * The result is written to `apps/docs/lib/product/apps.generated.json` by
 * `pnpm docs:product`, because the docs site builds on its own install and
 * cannot import `src/`; `test/docs-product-block.test.ts` fails when that file
 * is stale. There is no Traditional pack (AGENTS.md, zh-Hant rule), so the
 * zh-Hant name is authored beside the copy in `product.json`, as the zh-CN
 * wording written in Traditional characters.
 */

/** One app as the console names it. */
export type ProductApp = {
  /** The app's metadata name, such as `crm_enterprise`. */
  name: string;
  label: { en: string; 'zh-CN': string };
};

type AppLike = { name: string; label?: string };
type Bundle = Record<string, { apps?: Record<string, { label?: string } | undefined> } | undefined>;

/**
 * Every app the stack registers, in registration order, with its English label
 * and the label the zh-CN pack gives it. A missing zh-CN label is returned as
 * an empty string so the caller can name it rather than crash.
 */
export function readProductApps(stack: { apps?: unknown[]; translations?: unknown[] }): ProductApp[] {
  const apps = (stack.apps ?? []) as AppLike[];
  const bundles = (stack.translations ?? []) as Bundle[];
  const zhLabel = (name: string): string => {
    for (const bundle of bundles) {
      const label = bundle['zh-CN']?.apps?.[name]?.label;
      if (label) return label;
    }
    return '';
  };
  return apps.map((app) => ({
    name: app.name,
    label: { en: app.label ?? app.name, 'zh-CN': zhLabel(app.name) },
  }));
}

/** The generated file's text: stable key order, two-space indent, final newline. */
export function renderProductApps(apps: ProductApp[]): string {
  return `${JSON.stringify({ $comment: 'Generated by `pnpm docs:product` from src/*/apps/*.app.ts and the zh-CN packs. Do not edit.', apps }, null, 2)}\n`;
}
